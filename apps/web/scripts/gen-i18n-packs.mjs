const uiExtraPath = path.join(root, "ui-extra.json");
const uiExtra = fs.existsSync(uiExtraPath)
  ? JSON.parse(fs.readFileSync(uiExtraPath, "utf8"))
  : {};
for (const [k, v] of Object.entries(uiExtra)) {
  packs.ko[k] = v.ko;
  packs.en[k] = v.en ?? v.ko;
}

for (const [id, over] of Object.entries(overrides)) {
  packs[id] = { ...packs.en, ...over };
}

const keys = Object.keys(packs.en);
for (const loc of LOCALES) {
  const pack = packs[loc.id];
  if (!pack) throw new Error(`missing pack ${loc.id}`);
  for (const k of keys) {
    if (!(k in pack)) throw new Error(`${loc.id} missing ${k}`);
  }
  const file = path.join(root, "messages", `${loc.id}.ts`);
  const body =
    `import type { MessageDict } from "../types";\n\nconst messages: MessageDict = ${JSON.stringify(
      pack,
      null,
      2,
    )};\n\nexport default messages;\n`;
  writeAtomic(file, body);
}

const typesBody = `export const LOCALE_IDS = [
${LOCALES.map((l) => `  "${l.id}",`).join("\n")}
] as const;

export type LocaleId = (typeof LOCALE_IDS)[number];

export type MessageKey =
${keys.map((k) => `  | "${k}"`).join("\n")};

export type MessageDict = Record<MessageKey, string>;

export type LocaleMeta = {
  id: LocaleId;
  htmlLang: string;
  bcp47: string;
  nativeName: string;
  englishName: string;
  flagHint: string;
  rtl?: boolean;
};
`;

writeAtomic(path.join(root, "types.ts"), typesBody);

const localesBody = `import type { LocaleId, LocaleMeta } from "./types";
import { LOCALE_IDS } from "./types";

export const LOCALE_META: Record<LocaleId, LocaleMeta> = ${JSON.stringify(
  Object.fromEntries(LOCALES.map((l) => [l.id, l])),
  null,
  2,
)};

export function isLocaleId(value: string): value is LocaleId {
  return (LOCALE_IDS as readonly string[]).includes(value);
}

export { LOCALE_IDS };
`;

writeAtomic(path.join(root, "locales.ts"), localesBody);

